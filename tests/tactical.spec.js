const { test, expect } = require('@playwright/test');

test('Pestañas y preparación táctica: resolver, comprar y comenzar juntos', async ({ page, context }, testInfo) => {
  test.setTimeout(115000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Crear sala' })).toBeEnabled();
  await page.getByRole('tab', { name: 'Con puzzles', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Con puzzles', exact: true })).toHaveAttribute('aria-selected','true');
  await page.locator('#nickname').fill('Táctico');
  await page.locator('#match-bots').selectOption('5');
  await page.getByRole('button', { name: 'Crear sala' }).click();
  const guest = await context.newPage();
  await guest.goto('/');
  await expect(guest.getByRole('tab', { name: 'Con puzzles', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(guest.getByRole('tab', { name: 'Clásico', exact: true })).toBeDisabled();
  await guest.locator('#nickname').fill('Invitado táctico');
  await guest.getByRole('button', { name: 'Unirse a la sala' }).click();
  await expect(page.locator('#room-players li')).toHaveCount(2);
  await page.getByRole('button', { name: 'Iniciar partida', exact: true }).click();
  await expect(page.locator('#tactical-screen')).toBeVisible();
  await expect(guest.locator('#tactical-screen')).toBeVisible();
  await expect(page.locator('#training-intro')).toBeVisible();
  await expect(guest.locator('#training-intro')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('training-instructions.png'), fullPage: true });
  await expect(page.locator('#training-intro')).toBeHidden({ timeout: 8000 });
  const mapBox = await page.locator('#training-map').boundingBox();
  const titleBox = await page.locator('#tactical-title').boundingBox();
  const panelBox = await page.locator('.tactical-panel').boundingBox();
  expect(mapBox.y).toBeGreaterThan(titleBox.y + titleBox.height);
  expect(mapBox.x).toBeGreaterThanOrEqual(panelBox.x);
  expect(mapBox.x + mapBox.width).toBeLessThanOrEqual(panelBox.x + panelBox.width);
  await expect(page.locator('#tactical-credits')).toHaveText('80');
  await page.bringToFront();
  const startX = await page.evaluate(() => tacticalState.players[network.id].training.player.x);
  await page.keyboard.down('KeyD');
  await page.waitForFunction(x => tacticalState.players[network.id].training.player.x > x + 25, startX);
  await page.keyboard.up('KeyD');
  const privateHost = await page.evaluate(() => ({ ids: Object.keys(tacticalState.players), id: network.id, beacons: tacticalState.players[network.id].training.beacons }));
  const privateGuest = await guest.evaluate(() => ({ ids: Object.keys(tacticalState.players), id: network.id, beacons: tacticalState.players[network.id].training.beacons }));
  expect(privateHost.ids).toEqual([privateHost.id]);
  expect(privateGuest.ids).toEqual([privateGuest.id]);
  expect(privateHost.beacons).not.toEqual(privateGuest.beacons);
  await page.evaluate(() => {
    window.trainingPilot = setInterval(() => {
      const account = tacticalState?.players[network.id];
      for (const key of ['KeyW','KeyA','KeyS','KeyD']) keys.delete(key);
      if (!account?.training || account.credits >= 100) return;
      const room = account.training, beacon = room.beacons.find(b => b.id === room.active);
      if (!beacon) return;
      if (beacon.x - room.player.x > 8) keys.add('KeyD');
      if (beacon.x - room.player.x < -8) keys.add('KeyA');
      if (beacon.y - room.player.y > 8) keys.add('KeyS');
      if (beacon.y - room.player.y < -8) keys.add('KeyW');
    }, 50);
  });
  await page.waitForFunction(() => tacticalState.players[network.id].credits >= 100, null, { timeout: 50000 });
  await page.evaluate(() => { clearInterval(window.trainingPilot); keys.clear(); });
  await page.screenshot({ path: testInfo.outputPath('puzzles.png'), fullPage: true });
  await expect(page.locator('#shop-area')).toBeVisible({ timeout: 65000 });
  await expect(guest.locator('#shop-area')).toBeVisible();
  const before = Number(await page.locator('#tactical-credits').textContent());
  await page.locator('#shop-area article').filter({ has: page.getByRole('heading', { name: 'Rifle', exact: true }) }).getByRole('button').click();
  await expect(page.locator('#tactical-credits')).toHaveText(String(before - 100));
  expect(await page.evaluate(() => jugadores[network.id].inventario.includes('rifle'))).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('shop.png'), fullPage: true });
  await expect(page.locator('#match-countdown')).toBeVisible({ timeout: 25000 });
  await expect(page.locator('#tactical-screen')).toBeHidden();
  await expect(page.locator('#match-countdown')).toBeHidden({ timeout: 8000 });
  expect(await page.evaluate(() => jugadores[network.id].inventario.includes('rifle'))).toBe(true);
  expect(errors).toEqual([]);
  await guest.close();
});
